#define HANGUL_COUNT (sizeof(HANGUL_GLYPHS)/sizeof(HANGUL_GLYPHS[0]))

static inline const uint8_t* get_glyph_bitmap(uint32_t cp) {
    if (cp >= 32 && cp <= 127) {
        return FONT_8X8[cp - 32];
    }
    // Cyrillic (А-Я, а-я, Ё, ё)
    if (cp >= 0x0410 && cp <= 0x042F) {
        return CYRILLIC_8X8[cp - 0x0410]; // 0..31
    }
    if (cp >= 0x0430 && cp <= 0x044F) {
        return CYRILLIC_8X8[32 + (cp - 0x0430)]; // 32..63
    }
    if (cp == 0x0401) return CYRILLIC_8X8[64]; // Ё
    if (cp == 0x0451) return CYRILLIC_8X8[65]; // ё

    // Hangul (Korean)
    if (cp >= 0xAC00) {
        for (size_t i = 0; i < HANGUL_COUNT; i++) {
            if (HANGUL_GLYPHS[i].cp == cp) return HANGUL_GLYPHS[i].data;
        }
    }

    return FONT_8X8['?' - 32];
}

// UTF-8 Decoder & Length Helper
static inline int get_utf8_char(const char *str, uint32_t *out_cp) {
    unsigned char c = (unsigned char)str[0];
    if (c == 0) return 0;
    if (c < 0x80) {
        *out_cp = c;
        return 1;
    }
    if ((c & 0xE0) == 0xC0) {
        unsigned char c2 = (unsigned char)str[1];
        if (c2 == 0) { *out_cp = '?'; return 1; }
        *out_cp = ((c & 0x1F) << 6) | (c2 & 0x3F);
        return 2;
    }
    if ((c & 0xF0) == 0xE0) {
        unsigned char c2 = (unsigned char)str[1];
        unsigned char c3 = (unsigned char)str[2];
        if (c2 == 0 || c3 == 0) { *out_cp = '?'; return 1; }
        *out_cp = ((c & 0x0F) << 12) | ((c2 & 0x3F) << 6) | (c3 & 0x3F);
        return 3;
    }
    *out_cp = '?';
    return 1;
}

// Helper: Calculate pixel width of UTF-8 string at scale
static inline int text_utf8_width(const char *text, int scale) {
    if (!text) return 0;
    int count = 0;
    const char *p = text;
    uint32_t cp = 0;
    while (*p) {
        int bytes = get_utf8_char(p, &cp);
        if (bytes <= 0) break;
        p += bytes;
        count++;
    }
    if (count == 0) return 0;
    return count * 9 * scale - scale;
}

static inline void draw_text_bitmap(const char *text, int start_x, int start_y, int scale, Color color) {
    if (!text) return;
    const char *p = text;
    int cur_x = start_x;
    uint32_t cp = 0;

    while (*p) {
        int bytes = get_utf8_char(p, &cp);
        if (bytes <= 0) break;
        p += bytes;

        const uint8_t *glyph = get_glyph_bitmap(cp);
        for (int row = 0; row < 8; row++) {
            uint8_t line = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (line & (0x80 >> col)) {
                    if (scale == 1) {
                        DrawPixel(cur_x + col, start_y + row, color);
                    } else {
                        DrawRectangle(cur_x + col * scale, start_y + row * scale, scale, scale, color);
                    }
                }
            }
        }
        cur_x += 8 * scale + scale; // 9 * scale per character
    }
}

