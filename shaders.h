// FS_BACKGROUND: Cinematic Cosmic Void with Volumetric Nebulae & Multi-Layer Starfield
static const char *FS_BACKGROUND =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform float u_time;\n"
"uniform vec2 u_resolution;\n"
"\n"
"float hash(vec2 p) { return fract(sin(dot(p, vec2(12.9898, 78.233))) * 43758.5453); }\n"
"float noise(vec2 p) {\n"
"    vec2 i = floor(p); vec2 f = fract(p); f = f*f*(3.0-2.0*f);\n"
"    return mix(mix(hash(i), hash(i+vec2(1,0)), f.x), mix(hash(i+vec2(0,1)), hash(i+vec2(1,1)), f.x), f.y);\n"
"}\n"
"float fbm(vec2 p) {\n"
"    float v = 0.0, a = 0.5;\n"
"    for (int i = 0; i < 5; i++) { v += a * noise(p); p *= 2.1; a *= 0.5; }\n"
"    return v;\n"
"}\n"
"\n"
"void main() {\n"
"    vec2 uv = gl_FragCoord.xy / u_resolution;\n"
"    vec2 st = (gl_FragCoord.xy - 0.5 * u_resolution) / u_resolution.y;\n"
"\n"
"    // Deep space gradient\n"
"    vec3 col = mix(vec3(0.02, 0.03, 0.09), vec3(0.05, 0.01, 0.12), uv.y);\n"
"\n"
"    // Volumetric nebulae using layered FBM\n"
"    vec2 nb1 = st * 1.8 + vec2(u_time * 0.012, u_time * 0.008);\n"
"    float n1 = fbm(nb1) * fbm(nb1 * 1.5 + 3.7);\n"
"    vec3 neb_cold = vec3(0.0, 0.15, 0.35);\n"
"    vec3 neb_warm = vec3(0.22, 0.0, 0.28);\n"
"    col += mix(neb_cold, neb_warm, fbm(st * 2.0 + u_time * 0.015)) * n1 * 0.7;\n"
"\n"
"    // Secondary faint nebula glow\n"
"    vec2 nb2 = st * 3.2 + vec2(-u_time * 0.009, u_time * 0.006);\n"
"    float n2 = fbm(nb2);\n"
"    col += vec3(0.08, 0.02, 0.15) * n2 * n2 * 0.5;\n"
"\n"
"    // Sparse starfield — cosmic void with few distant stars\n"
"    float s1 = hash(floor(uv * 260.0));\n"
"    if (s1 > 0.960) {\n"
"        float tw = sin(u_time * 4.5 + s1 * 200.0) * 0.4 + 0.6;\n"
"        col += vec3(0.90, 0.94, 1.0) * tw * (s1 - 0.960) * 45.0;\n"
"    }\n"
"    float s2 = hash(floor(uv * 400.0 + vec2(47, 89)));\n"
"    if (s2 > 0.978) {\n"
"        float tw = cos(u_time * 7.0 + s2 * 300.0) * 0.4 + 0.6;\n"
"        col += vec3(0.4, 0.75, 1.0) * tw * (s2 - 0.978) * 60.0;\n"
"    }\n"
"    float s3 = hash(floor(uv * 580.0 + vec2(19, 73)));\n"
"    if (s3 > 0.988) {\n"
"        float tw = sin(u_time * 10.0 + s3 * 180.0) * 0.4 + 0.6;\n"
"        col += vec3(0.7, 0.3, 1.0) * tw * (s3 - 0.988) * 70.0;\n"
"    }\n"
"\n"
"    finalColor = vec4(col, 1.0);\n"
"}\n";

// FS_ECHO_PULSE: Echolocation Wave Shader with Double-Ring & Bloom
static const char *FS_ECHO_PULSE =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform float u_time;\n"
"uniform vec2 u_resolution;\n"
"uniform vec2 u_pulse_origin;\n"
"uniform float u_pulse_radius;\n"
"uniform float u_pulse_intensity;\n"
"\n"
"void main() {\n"
"    vec2 uv = gl_FragCoord.xy / u_resolution;\n"
"    float aspect = u_resolution.x / u_resolution.y;\n"
"    vec2 st = uv; st.x *= aspect;\n"
"    vec2 orig = u_pulse_origin / u_resolution; orig.x *= aspect;\n"
"    float dist = length(st - orig);\n"
"\n"
"    vec4 col = vec4(0.0);\n"
"    float wave_thick = 0.04;\n"
"    float diff = abs(dist - u_pulse_radius);\n"
"    if (diff < wave_thick && u_pulse_intensity > 0.01) {\n"
"        float ring = (1.0 - diff / wave_thick);\n"
"        float alpha = ring * ring * u_pulse_intensity;\n"
"        col = vec4(0.0, 0.94, 1.0, alpha * 0.7);\n"
"    }\n"
"    // Secondary inner ring\n"
"    float diff2 = abs(dist - u_pulse_radius * 0.85);\n"
"    if (diff2 < wave_thick * 0.5 && u_pulse_intensity > 0.01) {\n"
"        float ring2 = (1.0 - diff2 / (wave_thick * 0.5));\n"
"        col += vec4(0.6, 0.2, 1.0, ring2 * ring2 * u_pulse_intensity * 0.35);\n"
"    }\n"
"    finalColor = col;\n"
"}\n";

// FS_POST_PROCESS: Cinematic Post-Processing — Bloom, Tone-mapping, Vignette, Film Grain, Chromatic Aberration
static const char *FS_POST_PROCESS =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform sampler2D texture0;\n"
"uniform float u_time;\n"
"uniform vec2 u_resolution;\n"
"uniform float u_distortion;\n"
"\n"
"float hash(vec2 p) { return fract(sin(dot(p, vec2(12.9898, 78.233))) * 43758.5453); }\n"
"\n"
"void main() {\n"
"    vec2 uv = fragTexCoord;\n"
"    vec2 center = vec2(0.5);\n"
"    float vdist = length(uv - center);\n"
"\n"
"    // Chromatic Aberration (very subtle baseline, stronger on hit)\n"
"    vec2 offset = vec2(0.0);\n"
"    float ca_amount = 0.0006 + u_distortion * 0.008;\n"
"    if (u_distortion > 0.01) {\n"
"        offset.x = sin(u_time * 40.0 + uv.y * 30.0) * u_distortion * 0.008;\n"
"        offset.y = cos(u_time * 35.0 + uv.x * 25.0) * u_distortion * 0.008;\n"
"    }\n"
"\n"
"    vec2 uv_r = uv + offset + vec2(ca_amount, 0.0);\n"
"    vec2 uv_g = uv + offset;\n"
"    vec2 uv_b = uv + offset - vec2(ca_amount, 0.0);\n"
"\n"
"    float r = texture(texture0, uv_r).r;\n"
"    float g = texture(texture0, uv_g).g;\n"
"    float b = texture(texture0, uv_b).b;\n"
"    vec3 color = vec3(r, g, b);\n"
"\n"
"    // Bloom: only very bright pixels glow (high threshold = text stays crisp)\n"
"    vec3 bloom = vec3(0.0);\n"
"    float bstep = 2.5 / u_resolution.x;\n"
"    for (int i = -3; i <= 3; i++) {\n"
"        for (int j = -3; j <= 3; j++) {\n"
"            if (i == 0 && j == 0) continue;\n"
"            vec2 off = vec2(float(i), float(j)) * bstep;\n"
"            vec3 s = texture(texture0, uv + off).rgb;\n"
"            float luma = dot(s, vec3(0.2126, 0.7152, 0.0722));\n"
"            if (luma > 0.72) bloom += (s - 0.72) * 0.045;\n"
"        }\n"
"    }\n"
"    color += bloom;\n"
"\n"
"    // ACES filmic tone-mapping\n"
"    color = (color * (2.51 * color + 0.03)) / (color * (2.43 * color + 0.59) + 0.14);\n"
"\n"
"    // Subtle color grading\n"
"    vec3 shadows = vec3(0.03, 0.06, 0.12);\n"
"    vec3 highlights = vec3(1.05, 0.98, 0.90);\n"
"    float luma = dot(color, vec3(0.2126, 0.7152, 0.0722));\n"
"    color = mix(color + shadows * (1.0 - luma) * 0.12, color * highlights, luma);\n"
"\n"
"    // Gentle vignette\n"
"    float vig = 1.0 - vdist * vdist * 0.7;\n"
"    color *= vig;\n"
"\n"
"    // Very subtle film grain\n"
"    float grain = (hash(uv * u_resolution + u_time * 100.0) - 0.5) * 0.025;\n"
"    color += grain;\n"
"\n"
"    finalColor = vec4(clamp(color, 0.0, 1.0), 1.0);\n"
"}\n";

